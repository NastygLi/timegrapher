#!/usr/bin/env python3
"""Inline web/analysis.js into web/index.html and write timegrapher/index_html.h.
Run after editing anything in web/, then re-upload the sketch."""
from pathlib import Path

root = Path(__file__).parent
html = (root / "web/index.html").read_text()
js = (root / "web/analysis.js").read_text()
tag = '<script src="analysis.js"></script>'
assert tag in html, "analysis.js script tag not found"
html = html.replace(tag, "<script>\n" + js + "</script>")
delim = "TGHTML"
assert f'){delim}"' not in html
out = root / "firmware/esp32_timegrapher/index_html.h"
out.write_text(
    "// Generated by embed.py from web/ -- do not edit by hand.\n#pragma once\n"
    f'static const char INDEX_HTML[] = R"{delim}(' + html + f'){delim}";\n'
)
print(f"wrote {out} ({len(html):,} bytes of HTML)")
